#!/usr/bin/env bash
# TravelCRM Pro — Sync Terraform outputs → wrangler.toml + .dev.vars
# Usage: npm run infra:sync (from project root)
#
# Reads terraform.tfvars + terraform output to generate:
#   1. backend/.dev.vars       — local dev secrets
#   2. Updates wrangler.toml   — replaces placeholder IDs with real ones
#
# Prerequisites: terraform must have been applied at least once.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
TF_DIR="$PROJECT_ROOT/terraform"
BACKEND_DIR="$PROJECT_ROOT/backend"
TFVARS="$TF_DIR/terraform.tfvars"

# ─── Check prerequisites ────────────────────────────────────

if [ ! -f "$TFVARS" ]; then
  echo "ERROR: $TFVARS not found."
  echo "  cp terraform/terraform.tfvars.example terraform/terraform.tfvars"
  echo "  Then fill in your values and run: cd terraform && terraform apply"
  exit 1
fi

echo "==> Reading terraform.tfvars for secrets..."

# Helper: extract value from tfvars (handles quoted strings)
tfvar() {
  grep "^${1}\s*=" "$TFVARS" 2>/dev/null | sed 's/^[^=]*=\s*"\?\([^"]*\)"\?\s*$/\1/' | head -1
}

# ─── Generate backend/.dev.vars ──────────────────────────────

echo "==> Generating backend/.dev.vars..."

cat > "$BACKEND_DIR/.dev.vars" << EOF
# Auto-generated by scripts/sync-config.sh — do NOT edit manually
# Source of truth: terraform/terraform.tfvars
# Regenerate: npm run infra:sync

JWT_SECRET=$(tfvar jwt_secret)
JWT_REFRESH_SECRET=$(tfvar jwt_refresh_secret)
TWILIO_ACCOUNT_SID=$(tfvar twilio_account_sid)
TWILIO_AUTH_TOKEN=$(tfvar twilio_auth_token)
TWILIO_VERIFY_SERVICE_SID=$(tfvar twilio_verify_service_sid)
TWILIO_SMS_FROM_NUMBER=$(tfvar twilio_sms_from_number)
TWILIO_WHATSAPP_FROM_NUMBER=$(tfvar twilio_whatsapp_from_number)
PLIVO_AUTH_ID=$(tfvar plivo_auth_id)
PLIVO_AUTH_TOKEN=$(tfvar plivo_auth_token)
PLIVO_SMS_FROM_NUMBER=$(tfvar plivo_sms_from_number)
PLIVO_WHATSAPP_FROM_NUMBER=$(tfvar plivo_whatsapp_from_number)
SENDGRID_API_KEY=$(tfvar sendgrid_api_key)
SENDGRID_FROM_EMAIL=$(tfvar sendgrid_from_email)
FCM_SERVER_KEY=$(tfvar fcm_server_key)
DEEPGRAM_API_KEY=$(tfvar deepgram_api_key)
ANTHROPIC_API_KEY=$(tfvar anthropic_api_key)
GOOGLE_MAPS_API_KEY=$(tfvar google_maps_api_key)
CF_ACCOUNT_ID=$(tfvar cloudflare_account_id)
CF_API_TOKEN=$(tfvar cloudflare_api_token)
APP_URL=$(tfvar app_url)

# Local dev only. Enables POST /api/v1/test/reset, which the Playwright suites
# use to reset to a clean, deterministic database. Never set in staging/prod —
# it is checked at backend/src/routes/test.ts and 403s unless it is exactly
# "true". This file is only read by \`wrangler dev\`.
TEST_MODE=true
EOF

echo "    -> backend/.dev.vars written"

# ─── Sync wrangler.toml IDs from Terraform outputs ──────────

if command -v terraform &>/dev/null && [ -d "$TF_DIR/.terraform" ]; then
  echo "==> Reading terraform output for resource IDs..."
  cd "$TF_DIR"

  D1_ID=$(terraform output -raw d1_master_database_id 2>/dev/null || echo "")
  KV_CACHE_ID=$(terraform output -raw kv_cache_id 2>/dev/null || echo "")
  KV_SESSIONS_ID=$(terraform output -raw kv_sessions_id 2>/dev/null || echo "")
  KV_REPORT_CACHE_ID=$(terraform output -raw kv_report_cache_id 2>/dev/null || echo "")

  cd "$PROJECT_ROOT"

  if [ -n "$D1_ID" ]; then
    echo "    -> Updating wrangler.toml with Terraform resource IDs..."
    WRANGLER="$BACKEND_DIR/wrangler.toml"

    # Replace D1 database_id
    sed -i "s|database_id = \"a0000000-0000-0000-0000-000000000001\"|database_id = \"$D1_ID\"|" "$WRANGLER"
    sed -i "s|database_id = \"[0-9a-f-]\{36\}\"|database_id = \"$D1_ID\"|" "$WRANGLER" 2>/dev/null || true

    # Replace KV namespace IDs
    if [ -n "$KV_CACHE_ID" ]; then
      sed -i "/binding = \"CACHE\"/{n;s|id = \"[^\"]*\"|id = \"$KV_CACHE_ID\"|}" "$WRANGLER"
    fi
    if [ -n "$KV_SESSIONS_ID" ]; then
      sed -i "/binding = \"SESSIONS\"/{n;s|id = \"[^\"]*\"|id = \"$KV_SESSIONS_ID\"|}" "$WRANGLER"
    fi
    if [ -n "$KV_REPORT_CACHE_ID" ]; then
      sed -i "/binding = \"REPORT_CACHE\"/{n;s|id = \"[^\"]*\"|id = \"$KV_REPORT_CACHE_ID\"|}" "$WRANGLER"
    fi

    echo "    -> wrangler.toml updated"
  else
    echo "    -> SKIP: No terraform outputs yet (run terraform apply first)"
  fi
else
  echo "    -> SKIP: terraform not initialized (run cd terraform && terraform init && terraform apply)"
fi

echo ""
echo "Done! Next steps:"
echo "  npm run dev           # Start all services locally"
echo "  npm run secrets:push  # Push secrets to Cloudflare (production)"
echo "  npm run deploy        # Deploy all services"
