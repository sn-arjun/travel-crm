#!/usr/bin/env node
/**
 * Generates the phone country tables from ONE source list (scripts/countries-source.json).
 *
 *   node scripts/gen-countries.mjs
 *
 * Source rows: [iso2, name, dial, minNational, maxNational, 'z'?]
 *   dial          calling code digits without '+' (NANP territories carry their area code, e.g. 1684)
 *   min/max       length of the national number AFTER the dial digits (trunk prefix excluded)
 *   'z'           the leading 0 is part of the number (Italy, Vatican, San Marino): never strip it
 *
 * The helper code comes from scripts/countries-body.ts.txt and scripts/countries-body.dart.txt.
 * Outputs (do not edit by hand):
 *   backend/src/utils/countries.ts
 *   desktop/src/lib/countries.ts
 *   packages/shared/lib/constants/countries.dart
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8').replace(/\r\n/g, '\n');
const rows = JSON.parse(read('scripts/countries-source.json'));
const q = (s) => JSON.stringify(s);

const tsRows = rows
  .map(
    ([iso, name, dial, min, max, z]) =>
      `  { iso: ${q(iso)}, name: ${q(name)}, dial: ${q(dial)}, min: ${min}, max: ${max}${z ? ', keepZero: true' : ''} },`,
  )
  .join('\n');

const tsHead = `/**
 * Phone country table: every country and territory with its own calling code and the length range of its
 * national numbers. GENERATED by scripts/gen-countries.mjs from scripts/countries-source.json. Do not edit.
 * The backend, the desktop app and the driver app (packages/shared) are generated from the same list.
 */

export interface PhoneCountry {
  /** ISO 3166-1 alpha-2. */
  iso: string;
  name: string;
  /** Calling code digits without '+'. NANP territories include their area code (1684). */
  dial: string;
  /** Shortest and longest national number, in digits, after the calling code (trunk prefix excluded). */
  min: number;
  max: number;
  /** The leading 0 belongs to the number (Italy): never treated as a trunk prefix. */
  keepZero?: boolean;
}

/** The country assumed when an agency has not chosen one (the product's launch market). */
export const DEFAULT_COUNTRY_ISO = 'IN';

export const COUNTRIES: readonly PhoneCountry[] = [
${tsRows}
];

`;

const desktopExtra = `
/** Flag emoji for an ISO alpha-2 code; '' for anything else. */
export function flagOf(iso: string): string {
  const code = (iso ?? '').toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return '';
  return String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}
`;

const body = read('scripts/countries-body.ts.txt');
writeFileSync(resolve(root, 'backend/src/utils/countries.ts'), tsHead + body);
writeFileSync(resolve(root, 'desktop/src/lib/countries.ts'), tsHead + body + desktopExtra);

const dq = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const dartRows = rows
  .map(
    ([iso, name, dial, min, max, z]) =>
      `  PhoneCountry(${dq(name)}, ${dq(iso)}, ${dq(dial)}, ${min}, ${max}${z ? ', keepZero: true' : ''}),`,
  )
  .join('\n');

const dartHead = `/// Phone country table: every country and territory with its own calling code and the length range of its
/// national numbers. GENERATED by scripts/gen-countries.mjs from scripts/countries-source.json. Do not edit.
/// The backend, the desktop app and the driver app are generated from the same list.
library;

class PhoneCountry {
  final String name;

  /// ISO 3166-1 alpha-2.
  final String iso;

  /// Calling code digits without '+'. NANP territories include their area code (1684).
  final String dialDigits;

  /// Shortest and longest national number after the calling code (trunk prefix excluded).
  final int minLength;
  final int maxLength;

  /// The leading 0 belongs to the number (Italy): never treated as a trunk prefix.
  final bool keepZero;

  const PhoneCountry(this.name, this.iso, this.dialDigits, this.minLength, this.maxLength,
      {this.keepZero = false});

  /// Calling code with the leading '+'.
  String get dial => '+$dialDigits';

  /// Flag emoji built from the ISO alpha-2 code.
  String get flag => String.fromCharCodes(
      iso.toUpperCase().codeUnits.map((c) => 0x1F1E6 + (c - 0x41)));

  @override
  String toString() => '$name ($dial)';
}

const List<PhoneCountry> kPhoneCountries = [
${dartRows}
];

`;
writeFileSync(resolve(root, 'packages/shared/lib/constants/countries.dart'), dartHead + read('scripts/countries-body.dart.txt'));
console.log(`generated ${rows.length} countries`);
