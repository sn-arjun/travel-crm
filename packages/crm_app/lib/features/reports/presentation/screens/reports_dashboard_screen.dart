import 'package:flutter/material.dart';
import 'package:go_router/go_router.dart';

class ReportsDashboardScreen extends StatelessWidget {
  const ReportsDashboardScreen({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Reports & Analytics'),
        centerTitle: false,
      ),
      body: LayoutBuilder(
        builder: (context, constraints) {
          final isDesktop = constraints.maxWidth > 800;
          return ListView(
            padding: const EdgeInsets.all(24.0),
            children: [
              _buildCategorySection(
                context, 
                'Sales & Financial', 
                Icons.attach_money,
                [
                  _ReportItem('Sales Summary', '/reports/sales-summary', 'Overview of won deals and lost opportunities.'),
                  _ReportItem('Win/Loss Analysis', '/reports/win-loss', 'Conversion rates grouped by salesperson.'),
                  _ReportItem('Revenue Summary', '/reports/revenue-summary', 'Recognized revenue based on payment clearing.'),
                  _ReportItem('Collections Report', '/reports/collections', 'Outstanding invoice balances and aging.'),
                  _ReportItem('Tax Collection Report', '/reports/tax', 'VAT collected vs Input VAT.'),
                ],
                isDesktop
              ),
              const SizedBox(height: 32),
              
              _buildCategorySection(
                context, 
                'Leads & Customers', 
                Icons.people,
                [
                  _ReportItem('Pipeline Summary', '/reports/pipeline-summary', 'Active leads by pipeline stage.'),
                  _ReportItem('Lead Ageing', '/reports/lead-ageing', 'How long leads have stayed open.'),
                  _ReportItem('Lead Velocity', '/reports/lead-velocity', 'Growth rate of qualified leads month over month.'),
                  _ReportItem('Customer LTV', '/reports/customer-ltv', 'Lifetime value generated per customer.'),
                ],
                isDesktop
              ),
              const SizedBox(height: 32),

              _buildCategorySection(
                context, 
                'Operations & Team', 
                Icons.work,
                [
                  _ReportItem('Team Performance', '/reports/team-performance', 'Won deals and completed tasks per member.'),
                  _ReportItem('Fleet Utilization', '/reports/fleet-utilization', 'Vehicle usage and trips mapped to active bookings.'),
                  _ReportItem('Supplier Usage', '/reports/supplier-usage', 'Volume of bookings given to each supplier.'),
                  _ReportItem('Visa Status', '/reports/visa-status', 'Overview of active visa application statuses.'),
                  _ReportItem('Campaign Performance', '/reports/campaign-performance', 'Leads generated by marketing campaigns.'),
                ],
                isDesktop
              ),
            ],
          );
        }
      ),
    );
  }

  Widget _buildCategorySection(BuildContext context, String title, IconData icon, List<_ReportItem> reports, bool isDesktop) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Container(
              padding: const EdgeInsets.all(8),
              decoration: BoxDecoration(
                color: Theme.of(context).colorScheme.primaryContainer,
                borderRadius: BorderRadius.circular(8),
              ),
              child: Icon(icon, color: Theme.of(context).colorScheme.onPrimaryContainer),
            ),
            const SizedBox(width: 12),
            Text(
              title, 
              style: Theme.of(context).textTheme.headlineSmall?.copyWith(
                fontWeight: FontWeight.bold,
              ),
            ),
          ],
        ),
        const SizedBox(height: 16),
        isDesktop 
          ? Wrap(
              spacing: 16,
              runSpacing: 16,
              children: reports.map((r) => SizedBox(
                width: 320, 
                child: _buildReportCard(context, r)
              )).toList(),
            )
          : Column(
              children: reports.map((r) => Padding(
                padding: const EdgeInsets.only(bottom: 12),
                child: _buildReportCard(context, r),
              )).toList(),
            ),
      ],
    );
  }

  Widget _buildReportCard(BuildContext context, _ReportItem report) {
    return Card(
      elevation: 0,
      shape: RoundedRectangleBorder(
        side: BorderSide(color: Theme.of(context).colorScheme.outlineVariant),
        borderRadius: BorderRadius.circular(12),
      ),
      child: InkWell(
        onTap: () => context.push(report.route),
        borderRadius: BorderRadius.circular(12),
        child: Padding(
          padding: const EdgeInsets.all(16.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Expanded(
                    child: Text(
                      report.title,
                      style: Theme.of(context).textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.w600,
                      ),
                    ),
                  ),
                  const Icon(Icons.arrow_forward_ios, size: 16),
                ],
              ),
              const SizedBox(height: 8),
              Text(
                report.description,
                style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                  color: Theme.of(context).colorScheme.onSurfaceVariant,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

class _ReportItem {
  final String title;
  final String route;
  final String description;

  _ReportItem(this.title, this.route, this.description);
}
