import type { DrizzleD1Database } from 'drizzle-orm/d1';
import type { TokenPayload } from './utils/jwt';

export interface Env {
  // D1 Databases
  MASTER_DB: D1Database;

  // R2 Buckets
  FILE_STORAGE: R2Bucket;

  // KV Namespaces
  CACHE: KVNamespace;
  SESSIONS: KVNamespace;
  REPORT_CACHE: KVNamespace;

  // Queues
  EMAIL_QUEUE: Queue;
  SMS_QUEUE: Queue;
  PUSH_NOTIFICATION_QUEUE: Queue;
  WP_PROVISION_QUEUE: Queue;
  IMPORT_QUEUE: Queue;
  EXPORT_QUEUE: Queue;
  CAMPAIGN_QUEUE: Queue;
  AI_EXTRACTION_QUEUE: Queue;
  AI_EXTRACTION_DLQ: Queue;
  TENANT_JOBS_QUEUE?: Queue;

  // Durable Objects
  REALTIME: DurableObjectNamespace;

  // AI Bindings
  AI: Ai;

  // Environment Variables (Secrets)
  JWT_SECRET: string;
  JWT_REFRESH_SECRET: string;
  // Twilio (legacy default provider)
  TWILIO_ACCOUNT_SID: string;
  TWILIO_AUTH_TOKEN: string;
  TWILIO_VERIFY_SERVICE_SID: string;
  TWILIO_SMS_FROM_NUMBER: string;
  TWILIO_WHATSAPP_FROM_NUMBER: string;
  // Plivo (alternative provider — 78% cheaper for India)
  PLIVO_AUTH_ID?: string;
  PLIVO_AUTH_TOKEN?: string;
  PLIVO_SMS_FROM_NUMBER?: string;
  PLIVO_WHATSAPP_FROM_NUMBER?: string;
  // WhatsApp through Meta's Cloud API (R213). All optional: without them Meta works only for agencies that bring their own account.
  /** Platform system-user access token (agencies on the platform's WhatsApp account). */
  WHATSAPP_META_TOKEN?: string;
  /** Platform default sending phone number id (used when an agency has none of its own). */
  WHATSAPP_META_PHONE_NUMBER_ID?: string;
  /** The platform Meta app's secret: signs every webhook the platform app delivers (X-Hub-Signature-256). */
  WHATSAPP_META_APP_SECRET?: string;
  /** Verify token typed into the platform app's webhook settings (GET handshake). */
  WHATSAPP_META_VERIFY_TOKEN?: string;
  /** Graph API version, default v21.0. */
  WHATSAPP_META_GRAPH_VERSION?: string;
  SENDGRID_API_KEY: string;
  FCM_SERVER_KEY: string;
  DEEPGRAM_API_KEY: string;
  ANTHROPIC_API_KEY: string;
  GOOGLE_MAPS_API_KEY?: string;
  // Shared secret in the SendGrid Inbound Parse URL (/webhooks/inbound/email/:secret)
  INBOUND_EMAIL_SECRET?: string;
  /** R208: HMAC key of the public unsubscribe links in marketing messages (falls back to a key derived from JWT_SECRET). */
  UNSUB_SECRET?: string;
  TEST_MODE?: string;
  /** 'mock' selects the in-memory VoIP provider (never in production). */
  VOIP_PROVIDER?: string;
  /** R137: seconds the mock provider takes to approve a regulatory bundle (default 0). Mock only. */
  MOCK_BUNDLE_DELAY_SECONDS?: string;
  /** Comma-separated ISO country codes where calling is offered; default GB,US,AU,SG. '*' = all (non-production only). */
  VOIP_CALLING_COUNTRIES?: string;
  CF_ACCOUNT_ID?: string;
  CF_API_TOKEN?: string;

  // Tier 1 configuration (optional; declared once so parallel batches do not edit this file together)
  TENANCY_MODE?: string;
  ALLOW_SINGLE_TENANT_PRODUCTION?: string;
  ENVIRONMENT?: string;
  SUPER_ADMIN_EMAIL?: string;
  APP_URL?: string;
  QUOTES_URL?: string;
  /** R148: base of the public booking and self-service pages (default: APP_URL, giving APP_URL/book and APP_URL/trip). */
  PUBLIC_PAGES_URL?: string;
  /** R148: Cloudflare Turnstile secret for the public booking form. Unset = honeypot and fill-time checks only. */
  TURNSTILE_SECRET_KEY?: string;
  /** R148: Turnstile site key handed to the booking page so it can show the widget (public by design). */
  TURNSTILE_SITE_KEY?: string;
  /** R148: minimum seconds between opening the booking form and submitting it (default 3; 0 in test mode). */
  PUBLIC_BOOKING_MIN_FILL_SECONDS?: string;
  API_PUBLIC_URL?: string;
  /** R131: Cloudflare Email Service sending binding (`[[send_email]] name = "EMAIL"`). Absent locally unless declared. */
  EMAIL?: {
    send(message: Record<string, unknown>): Promise<{ messageId?: string } | undefined>;
  };
  /** R131: provider of the platform's own system mail: 'sendgrid' (default), 'cloudflare' or 'mock'. Agency mail is always SendGrid. */
  EMAIL_SYSTEM_PROVIDER?: string;
  /** R131: domain that receives agency replies through Cloudflare Email Routing, for example in.example.com. */
  EMAIL_INBOUND_DOMAIN?: string;
  EMAIL_FROM?: string;
  EMAIL_FROM_NAME?: string;
  PLATFORM_SUPPORT_EMAIL?: string;
  CORS_ORIGINS?: string;
  ALLOW_LOOPBACK_ORIGINS?: string;
  RATE_LIMIT_MULTIPLIER?: string;
  CREDENTIALS_KEYS?: string;
  CREDENTIALS_ACTIVE_KEY_ID?: string;
  TENANT_PROVISIONER?: string;
  CF_WORKER_SCRIPT_NAME?: string;
  SENDGRID_WEBHOOK_PUBLIC_KEY?: string;
  TURNSTILE_SECRET?: string;
  OTP_DELIVERY?: string;
  SUPER_ADMIN_JWT_SECRET?: string;
  /** R309: base URL of the WordPress provisioner on the Oracle VM, for example https://wp-provisioner.example.com (no path). */
  OCI_PROVISIONER_URL?: string;
  /** R309: shared secret for signing requests to the provisioner (a Worker secret; the provisioner holds the same value). */
  PROVISIONER_SECRET?: string;
  /** R309: domain under which agency sites live, for example sites.example.com gives acme.sites.example.com. */
  WP_SITES_DOMAIN?: string;
  ERROR_REPORTER_DSN?: string;
  /** Shared secret for GET /api/v1/health/deep when no super admin token is used. */
  HEALTH_TOKEN?: string;
  /** Hour (0-23, agency-local) at which daily agency jobs fire; default 9. */
  DAILY_JOB_HOUR?: string;
  APP_VERSION?: string;

  // Subscription billing (R205). Secrets: none of these have a default; a gateway with a missing secret refuses to work.
  /** 'mock' forces the in-process mock gateway (never in production). */
  BILLING_GATEWAY?: string;
  STRIPE_SECRET_KEY?: string;
  STRIPE_WEBHOOK_SECRET?: string;
  RAZORPAY_KEY_ID?: string;
  RAZORPAY_KEY_SECRET?: string;
  RAZORPAY_WEBHOOK_SECRET?: string;
  /** Signs mock-gateway events; falls back to a fixed local value when the mock gateway is allowed. */
  BILLING_MOCK_SECRET?: string;
  /** Platform tax on subscription invoices: where the platform is registered, its GST state / tax id, and the GST rate (default 18). */
  PLATFORM_TAX_COUNTRY?: string;
  PLATFORM_TAX_STATE?: string;
  PLATFORM_TAX_ID?: string;
  PLATFORM_GST_RATE?: string;
  /** Optional VAT on subscriptions for these buyer countries (comma list) at PLATFORM_VAT_RATE percent. */
  PLATFORM_VAT_COUNTRIES?: string;
  PLATFORM_VAT_RATE?: string;
  /** Days a failed renewal stays in grace before the agency turns read-only (default 7). */
  BILLING_GRACE_DAYS?: string;

  // Workers Rate Limiting bindings (generated wrangler config; absent in tests and plain wrangler dev)
  API_RATE_LIMITER?: { limit(options: { key: string }): Promise<{ success: boolean }> };
  UPLOAD_RATE_LIMITER?: { limit(options: { key: string }): Promise<{ success: boolean }> };

  // Dynamic tenant D1 bindings — resolved at runtime
  [key: `TENANT_DB_${string}`]: D1Database;
}

export interface AppContext {
  Bindings: Env;
  Variables: {
    userId: string;
    tenantId: string;
    requestId: string;
    tenantDb: D1Database;
    role: string;
    userName: string;
    jwtPayload: TokenPayload;
    clientIp: string;
    /** Set on /admin/* requests by the super admin auth (R111). */
    superAdmin: { id: string; email: string; name: string; role: string; tokenId: string };
    /** Set when a tenant request carries an impersonation token (R111): the super admin behind it. */
    impersonatedBy: { superAdminId: string; name: string; sessionId: string };
  };
}
