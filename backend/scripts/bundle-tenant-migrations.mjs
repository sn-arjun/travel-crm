#!/usr/bin/env node
/**
 * Bundle drizzle/tenant/*.sql into src/db/tenant-migrations.generated.ts so Worker code
 * (the R104 provisioner) can apply tenant migrations without a file system.
 *
 *   node scripts/bundle-tenant-migrations.mjs        (npm run db:bundle-tenant)
 *
 * Statements are split exactly as the test pool and wrangler split them (readD1Migrations),
 * comment-only statements are dropped (D1 rejects empty statements).
 */
import { readD1Migrations } from '@cloudflare/vitest-pool-workers/config';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const backendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrations = await readD1Migrations(path.join(backendDir, 'drizzle', 'tenant'));

const bundled = migrations.map((m) => ({
  name: m.name,
  // Line endings normalised so the bundle is identical on CRLF (Windows) and LF checkouts.
  queries: m.queries.map((q) => q.replace(/\r\n/g, '\n')).filter((q) => q.replace(/--[^\n]*/g, '').trim().length > 0),
}));

const body =
  `// AUTO-GENERATED by scripts/bundle-tenant-migrations.mjs from drizzle/tenant/*.sql. Do not edit.\n` +
  `// Re-run \`npm run db:bundle-tenant\` after adding a tenant migration (a unit test fails otherwise).\n\n` +
  `export interface BundledMigration {\n  name: string;\n  queries: string[];\n}\n\n` +
  `export const TENANT_MIGRATIONS: BundledMigration[] = ${JSON.stringify(bundled, null, 2)};\n`;

writeFileSync(path.join(backendDir, 'src', 'db', 'tenant-migrations.generated.ts'), body, 'utf8');
console.log(
  `bundle-tenant-migrations: ${bundled.length} migrations, ${bundled.reduce((n, m) => n + m.queries.length, 0)} statements`,
);
