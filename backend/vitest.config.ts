import { defineWorkersConfig, readD1Migrations } from '@cloudflare/vitest-pool-workers/config';
import fs from 'fs';
import path from 'path';

/**
 * [ui-remake] Generate a test-only wrangler config with the `[ai]` binding removed.
 *
 * Why: @cloudflare/vitest-pool-workers@0.5.21 bundles miniflare 3.20241230.0,
 * which cannot resolve `miniflare-internal:wrapped:__WRANGLER_EXTERNAL_AI_WORKER`.
 * Since commit 50e43e5 added `[ai] binding = "AI"` to wrangler.toml, the Workers
 * runtime fails to start and ZERO backend tests execute.
 *
 * Deriving the test config from wrangler.toml at load time (rather than keeping a
 * forked copy) means every other binding stays in sync automatically. Remove this
 * once the pool/miniflare versions support the AI binding.
 */
function writeTestWranglerConfig(): string {
    const source = path.resolve(__dirname, 'wrangler.toml');
    const target = path.resolve(__dirname, '.wrangler-test.toml');
    const lines = fs.readFileSync(source, 'utf8').split(/\r?\n/);

    const out: string[] = [];
    let skipping = false;
    for (const line of lines) {
        const isSectionHeader = /^\s*\[/.test(line);
        if (isSectionHeader) skipping = /^\s*\[ai\]/.test(line);
        if (!skipping) out.push(line);
    }

    fs.writeFileSync(
        target,
        `# AUTO-GENERATED by vitest.config.ts — do not edit. Source: wrangler.toml\n` +
            out.join('\n'),
        'utf8'
    );
    return './.wrangler-test.toml';
}

// Filter out comment-only queries that D1 rejects as empty statements
function stripEmptyQueries(migrations: { name: string; queries: string[] }[]) {
    return migrations.map(m => ({
        ...m,
        queries: m.queries.filter(q => q.replace(/--[^\n]*/g, '').trim().length > 0),
    }));
}

export default async () => {
    const masterPath = path.resolve(__dirname, 'drizzle/master');
    const masterMigrations = await readD1Migrations(masterPath);
    const tenantPath = path.resolve(__dirname, 'drizzle/tenant');
    const tenantMigrations = await readD1Migrations(tenantPath);

    const mergedMigrations = stripEmptyQueries([
        ...masterMigrations.map(m => ({ ...m, name: `master_${m.name}` })),
        ...tenantMigrations.map(m => ({ ...m, name: `tenant_${m.name}` }))
    ]);

    return defineWorkersConfig({
        test: {
            poolOptions: {
                workers: {
                    singleWorker: true,
                    isolatedStorage: false,
                    wrangler: { configPath: writeTestWranglerConfig() },
                    miniflare: {
                        bindings: {
                            TEST_MODE: 'true',
                            TEST_MIGRATIONS: mergedMigrations as any,
                        },
                    },
                },
            },
        },
    });
};
